use std::collections::BTreeMap;
use std::fmt::Write;

use crate::Category;
use crate::Linter;
use crate::Rule;

const HEADER: &str = "---
name: lele-lint-rules
description: Use when lele-lint reports LELE0xx errors, or before writing or reviewing Rust in a crate checked by lele-lint. One entry per rule with the fix to apply, listed in fix order. Generated from the linter, so it never drifts from it.
---

# lele-lint rules

Generated by `lele-lint --skill-md`; do not edit by hand. Regenerate with `just docs`.

This is the rule index: what each rule wants and how to fix it. For the design ideas behind
the rules (domains, atomic files, delegates), load the `lele-syntax-rs` skill. Bevy rules
(`LELEBEVY0xx`) are covered by the `bevy-ui-preview` skill.

## How to clear lint errors

1. Run the linter: `just lint`, or `lele-lint --config lele.toml <crate>`. Each error shows
   its file and line, a `help:` line with the fix for that exact site, and the run ends with
   the error count per rule.
2. Fix ONE rule code at a time, in the order of the sections below (layout first, style
   last). Between codes in the same section, start with the one that has the fewest errors.
3. Unsure what a rule wants? `lele-lint --explain <CODE>` prints a Bad and a Good example
   crate. Copy the Good shape.
4. Re-run the linter after each code: fixes cascade, so the list changes every time.
5. Never silence or loosen a rule: no `#[allow]`/`#[expect]`, no new exemptions or allow
   entries in `lele.toml`, `Cargo.toml` or `clippy.toml` (adding the required clippy
   baseline for LELE028/LELE029 is fine). If a fix seems to need one, stop and ask the user.

## Every file you create or edit

A fix for one rule must not break another. Before saving, check the file against this list
(most cascades come from new files):

- Named in snake_case after its one public item (LELE001, LELE002).
- Ends with `#[cfg(test)] mod tests` holding a `test_usage` test, or with
  `// no test_usage necessary` when there is nothing to test (LELE009).
- No comments (LELE031); no `#[allow]`/`#[expect]` (LELE024).
- Imports the domain, not the item (`use crate::stock;` then `stock::Item`, LELE016);
  no `super::` outside tests (LELE013); `crate::` only in `use` lines (LELE025).
- Helpers are `pub(crate)` methods of a type, never private or free fns (LELE008, LELE034).
- A data type with no `impl` goes in the domain's `__basic__/` (LELE020).
- A method body over 3 statements lives in `methods/<type>/<method>.rs` (LELE017, LELE030).

";

pub fn skill_markdown(linter: &Linter) -> String {
    let mut out = String::from(HEADER);
    let mut by_category: BTreeMap<Category, Vec<&Box<dyn Rule>>> = BTreeMap::new();
    for rule in &linter.rules {
        by_category
            .entry(rule.doc().category)
            .or_default()
            .push(rule);
    }
    for (category, mut in_category) in by_category {
        in_category.sort_by_key(|rule| rule.code());
        let _ = writeln!(out, "## {category}\n");
        for rule in in_category {
            let doc = rule.doc();
            let _ = writeln!(
                out,
                "- **{} `{}`**: {}",
                rule.code(),
                rule.name(),
                doc.summary
            );
            let _ = writeln!(out, "  - Fix: {}", doc.fix);
        }
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::skill_markdown;
    use crate::Linter;

    #[test]
    fn test_usage() {
        let linter = Linter::default();
        let text = skill_markdown(&linter);
        assert!(text.starts_with("---\nname: lele-lint-rules\n"));
        for rule in &linter.rules {
            assert!(text.contains(&format!("**{} `{}`**", rule.code(), rule.name())));
        }
    }
}
