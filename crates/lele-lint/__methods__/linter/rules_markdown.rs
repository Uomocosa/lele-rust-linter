use std::collections::BTreeMap;
use std::fmt::Write;

use crate::Category;
use crate::Linter;
use crate::Rule;

const HEADER: &str = "# lele_lint rules

Generated by `lele_lint --rules-md`; do not edit by hand. Regenerate with
`just docs` (the `rules_md` test fails while this file is stale).

Every rule is always on and always an error. `lele_lint --explain <CODE>` prints one rule.

Each example is a whole crate. Files not shown get these defaults: an empty `src/lib.rs`,
and a `Cargo.toml`, `clippy.toml` and `lele.toml` that already satisfy the clippy-config rules.
Every **Bad** example reports its rule's code (it may report others too);
every **Good** example reports nothing at all.

";

pub fn rules_markdown(linter: &Linter) -> String {
    let mut out = String::from(HEADER);
    let mut by_category: BTreeMap<Category, Vec<&Box<dyn Rule>>> = BTreeMap::new();
    for rule in &linter.rules {
        by_category
            .entry(rule.doc().category)
            .or_default()
            .push(rule);
    }
    for (category, mut in_category) in by_category {
        in_category.sort_by_key(|c| c.code());
        let _ = writeln!(out, "## {category}\n");
        for rule in &in_category {
            let _ = writeln!(
                out,
                "- [{} `{}`](#{}-{}): {}",
                rule.code(),
                rule.name(),
                rule.code().to_lowercase(),
                rule.name(),
                rule.doc().summary
            );
        }
        out.push('\n');
        for rule in in_category {
            out.push_str(&Linter::render_rule(rule.as_ref()));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::rules_markdown;
    use crate::Linter;

    #[test]
    fn test_usage() {
        let linter = Linter::default();
        let text = rules_markdown(&linter);
        assert!(text.starts_with("# lele_lint rules"));
        for rule in &linter.rules {
            assert!(text.contains(&format!("### {} `{}`", rule.code(), rule.name())));
        }
    }
}
